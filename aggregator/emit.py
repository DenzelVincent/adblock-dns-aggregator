"""产物渲染：四种格式 × lite/full 两档，固定排序、固定 LF。"""

from __future__ import annotations

from pathlib import Path

# 按软件分目录：mosdns 按 URL basename 落地，各档 basename 不同，互不覆盖（见设计 5.7）
FORMATS: dict[str, tuple[str, str, object]] = {
    "mosdns": ("txt", "#", lambda domain: domain),
    "adguard": ("txt", "!", lambda domain: f"||{domain}^"),
    "dnsmasq": ("conf", "#", lambda domain: f"address=/{domain}/0.0.0.0"),
    "smartdns": ("conf", "#", lambda domain: f"address /{domain}/#"),
}


def render(
    fmt: str,
    domains: list[str],
    tier: str,
    generated_at: str,
    fold: bool,
    sources_summary: str,
) -> str:
    _, comment, line_for = FORMATS[fmt]
    lines = [
        f"{comment} Generated by adblock-dns-aggregator at {generated_at}",
        f"{comment} tier: {tier} | fold: {'on' if fold else 'off'} | entries: {len(domains)}",
        f"{comment} sources: {sources_summary}",
        "",
        *(line_for(domain) for domain in domains),
    ]
    return "\n".join(lines) + "\n"


def write_all(
    out_dir: Path,
    tier_domains: dict[str, list[str]],
    generated_at: str,
    fold: bool,
    summaries: dict[str, str],
) -> list[dict]:
    out_dir.mkdir(parents=True, exist_ok=True)
    outputs: list[dict] = []
    for tier, domains in tier_domains.items():
        for fmt, (extension, _, _) in FORMATS.items():
            # 按软件分目录：各客户端的同名档位文件互不覆盖
            relative = f"{fmt}/{tier}.{extension}"
            path = out_dir / fmt / f"{tier}.{extension}"
            path.parent.mkdir(parents=True, exist_ok=True)
            text = render(fmt, domains, tier, generated_at, fold, summaries[tier])
            # 二进制写入：Windows 下避免 text 模式把 \n 变成 \r\n
            path.write_bytes(text.encode("utf-8"))
            outputs.append({"file": relative, "count": len(domains)})
    return outputs
