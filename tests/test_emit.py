from aggregator.emit import render, write_all

GENERATED_AT = "2026-11-12T20:00:00Z"
SOURCES = "fixture-lite (ok, 2 条)"


def test_mosdns_render():
    text = render("mosdns", ["example.com", "a.example.com"], "lite", GENERATED_AT, True, SOURCES)
    lines = text.splitlines()
    assert lines[0] == f"# Generated by adblock-dns-aggregator at {GENERATED_AT}"
    assert lines[1] == "# tier: lite | fold: on | entries: 2"
    assert lines[2] == f"# sources: {SOURCES}"
    assert lines[3] == ""
    assert lines[4:] == ["example.com", "a.example.com"]
    assert text.endswith("\n")


def test_adguard_render():
    text = render("adguard", ["example.com"], "full", GENERATED_AT, False, SOURCES)
    lines = text.splitlines()
    assert lines[0].startswith("! Generated by")
    assert lines[1] == "! tier: full | fold: off | entries: 1"
    assert lines[-1] == "||example.com^"


def test_dnsmasq_render():
    text = render("dnsmasq", ["example.com"], "lite", GENERATED_AT, True, SOURCES)
    assert text.splitlines()[-1] == "address=/example.com/0.0.0.0"


def test_smartdns_render():
    text = render("smartdns", ["example.com"], "lite", GENERATED_AT, True, SOURCES)
    assert text.splitlines()[-1] == "address /example.com/#"


def test_render_is_byte_stable():
    args = ("adguard", ["b.example.com", "a.example.com"], "lite", GENERATED_AT, True, SOURCES)
    assert render(*args) == render(*args)


def test_write_all_creates_eight_files(tmp_path):
    tiers = {"lite": ["example.com"], "full": ["example.com", "extra.example.org"]}
    outputs = write_all(tmp_path, tiers, GENERATED_AT, True, {"lite": SOURCES, "full": SOURCES})

    expected = {
        "mosdns-lite.txt",
        "mosdns-full.txt",
        "adguard-lite.txt",
        "adguard-full.txt",
        "dnsmasq-lite.conf",
        "dnsmasq-full.conf",
        "smartdns-lite.conf",
        "smartdns-full.conf",
    }
    assert {p.name for p in tmp_path.iterdir()} == expected
    assert [o["file"] for o in outputs] == [
        "mosdns-lite.txt",
        "adguard-lite.txt",
        "dnsmasq-lite.conf",
        "smartdns-lite.conf",
        "mosdns-full.txt",
        "adguard-full.txt",
        "dnsmasq-full.conf",
        "smartdns-full.conf",
    ]
    assert outputs[0]["count"] == 1
    assert outputs[4]["count"] == 2


def test_written_files_use_lf_only(tmp_path):
    write_all(
        tmp_path,
        {"lite": ["example.com"], "full": []},
        GENERATED_AT,
        True,
        {"lite": SOURCES, "full": SOURCES},
    )
    for path in tmp_path.iterdir():
        if path.suffix != ".json":
            assert b"\r\n" not in path.read_bytes(), path.name
